-- Assign IDs in Postgres so simultaneous inserts cannot choose the same ID.
ALTER TABLE public.baby_budget_items ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;
SELECT setval(
  pg_get_serial_sequence('public.baby_budget_items', 'id'),
  GREATEST(COALESCE(MAX(id), 0) + 1, 1),
  false
) FROM public.baby_budget_items;
NOTIFY pgrst, 'reload schema';
